"""Formatters for converting word-level Whisper segments into various subtitle formats."""

import json
import os
from typing import Dict, List, Optional
from video_to_subtitle.engine import SegmentTiming


def format_timestamp_srt(seconds: float) -> str:
    """Format seconds into SRT timestamp: HH:MM:SS,mmm"""
    total_ms = int(round(seconds * 1000))
    hours = total_ms // 3_600_000
    minutes = (total_ms % 3_600_000) // 60_000
    secs = (total_ms % 60_000) // 1000
    ms = total_ms % 1000
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{ms:03d}"


def format_timestamp_vtt(seconds: float) -> str:
    """Format seconds into WebVTT timestamp: HH:MM:SS.mmm"""
    total_ms = int(round(seconds * 1000))
    hours = total_ms // 3_600_000
    minutes = (total_ms % 3_600_000) // 60_000
    secs = (total_ms % 60_000) // 1000
    ms = total_ms % 1000
    return f"{hours:02d}:{minutes:02d}:{secs:02d}.{ms:03d}"


def format_timestamp_ass(seconds: float) -> str:
    """Format seconds into ASS timestamp: H:MM:SS.cc (centiseconds)"""
    total_cs = int(round(seconds * 100))
    hours = total_cs // 360_000
    minutes = (total_cs % 360_000) // 6000
    secs = (total_cs % 6000) // 100
    cs = total_cs % 100
    return f"{hours}:{minutes:02d}:{secs:02d}.{cs:02d}"


def to_srt(segments: List[SegmentTiming], word_level: bool = False) -> str:
    """
    Generate SubRip (.srt) subtitle string.
    If word_level=True, emits each word as a distinct subtitle entry.
    """
    lines = []
    counter = 1

    if word_level:
        for seg in segments:
            if seg.words:
                for w in seg.words:
                    clean_word = w.word.strip()
                    if not clean_word:
                        continue
                    start_str = format_timestamp_srt(w.start)
                    end_str = format_timestamp_srt(w.end)
                    lines.append(f"{counter}\n{start_str} --> {end_str}\n{clean_word}\n")
                    counter += 1
            else:
                start_str = format_timestamp_srt(seg.start)
                end_str = format_timestamp_srt(seg.end)
                lines.append(f"{counter}\n{start_str} --> {end_str}\n{seg.text}\n")
                counter += 1
    else:
        for seg in segments:
            clean_text = seg.text.strip()
            if not clean_text:
                continue
            start_str = format_timestamp_srt(seg.start)
            end_str = format_timestamp_srt(seg.end)
            lines.append(f"{counter}\n{start_str} --> {end_str}\n{clean_text}\n")
            counter += 1

    return "\n".join(lines).strip() + "\n"


def to_vtt(segments: List[SegmentTiming], word_level: bool = False) -> str:
    """Generate WebVTT (.vtt) subtitle string."""
    lines = ["WEBVTT\n"]
    counter = 1

    if word_level:
        for seg in segments:
            if seg.words:
                for w in seg.words:
                    clean_word = w.word.strip()
                    if not clean_word:
                        continue
                    start_str = format_timestamp_vtt(w.start)
                    end_str = format_timestamp_vtt(w.end)
                    lines.append(f"{counter}\n{start_str} --> {end_str}\n{clean_word}\n")
                    counter += 1
            else:
                start_str = format_timestamp_vtt(seg.start)
                end_str = format_timestamp_vtt(seg.end)
                lines.append(f"{counter}\n{start_str} --> {end_str}\n{seg.text}\n")
                counter += 1
    else:
        for seg in segments:
            clean_text = seg.text.strip()
            if not clean_text:
                continue
            start_str = format_timestamp_vtt(seg.start)
            end_str = format_timestamp_vtt(seg.end)
            lines.append(f"{counter}\n{start_str} --> {end_str}\n{clean_text}\n")
            counter += 1

    return "\n".join(lines).strip() + "\n"


def to_ass_karaoke(
    segments: List[SegmentTiming],
    title: str = "Video Subtitles",
    font_name: str = "Arial",
    font_size: int = 24,
    primary_color: str = "&H00FFFFFF",
    secondary_color: str = "&H0000FFFF",
    outline_color: str = "&H00000000",
    back_color: str = "&H80000000",
    bold: bool = True,
    alignment: int = 2,
    margin_v: int = 60,
) -> str:
    """
    Generate Advanced SubStation Alpha (.ass) with word-level karaoke timing.
    Uses {\\k<duration_centiseconds>} tags for animated highlighting.
    """
    bold_flag = -1 if bold else 0
    header = f"""[Script Info]
; Script generated by Video-to-Subtitle Studio
Title: {title}
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: None
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: KaraokeDefault,{font_name},{font_size},{primary_color},{secondary_color},{outline_color},{back_color},{bold_flag},0,0,0,100,100,0,0,1,3,2,{alignment},40,40,{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = []
    for seg in segments:
        if not seg.text.strip():
            continue
        start_time = format_timestamp_ass(seg.start)
        end_time = format_timestamp_ass(seg.end)

        if seg.words:
            karaoke_text_parts = []
            prev_end = seg.start
            for w in seg.words:
                # Account for any silence gap between words
                gap_cs = max(0, int(round((w.start - prev_end) * 100)))
                duration_cs = max(1, int(round((w.end - w.start) * 100)))
                if gap_cs > 0:
                    karaoke_text_parts.append(f"{{\\k{gap_cs}}}")
                # Karaoke tag precedes each word
                word_clean = w.word
                karaoke_text_parts.append(f"{{\\kf{duration_cs}}}{word_clean}")
                prev_end = w.end

            full_line_text = "".join(karaoke_text_parts)
        else:
            duration_cs = max(1, int(round((seg.end - seg.start) * 100)))
            full_line_text = f"{{\\kf{duration_cs}}}{seg.text}"

        events.append(
            f"Dialogue: 0,{start_time},{end_time},KaraokeDefault,,0,0,0,,{full_line_text}"
        )

    return header + "\n".join(events) + "\n"


def to_json(segments: List[SegmentTiming], info: Optional[dict] = None) -> str:
    """Generate structured JSON representation containing word-level timestamps."""
    data = {
        "metadata": info or {},
        "segments": [seg.to_dict() for seg in segments],
    }
    return json.dumps(data, indent=2, ensure_ascii=False)


def export_all_formats(
    segments: List[SegmentTiming],
    info: dict,
    output_dir: str,
    base_name: str,
    font_name: str = "Arial",
    font_size: int = 24,
    primary_color: str = "&H00FFFFFF",
    secondary_color: str = "&H0000FFFF",
    outline_color: str = "&H00000000",
    back_color: str = "&H80000000",
    bold: bool = True,
) -> Dict[str, str]:
    """Export all subtitle formats to output directory and return paths."""
    os.makedirs(output_dir, exist_ok=True)
    paths = {}

    # Standard SRT
    srt_path = os.path.join(output_dir, f"{base_name}.srt")
    with open(srt_path, "w", encoding="utf-8") as f:
        f.write(to_srt(segments, word_level=False))
    paths["srt"] = srt_path

    # Word-level SRT
    word_srt_path = os.path.join(output_dir, f"{base_name}.word.srt")
    with open(word_srt_path, "w", encoding="utf-8") as f:
        f.write(to_srt(segments, word_level=True))
    paths["word_srt"] = word_srt_path

    # WebVTT
    vtt_path = os.path.join(output_dir, f"{base_name}.vtt")
    with open(vtt_path, "w", encoding="utf-8") as f:
        f.write(to_vtt(segments, word_level=False))
    paths["vtt"] = vtt_path

    # ASS Karaoke
    ass_path = os.path.join(output_dir, f"{base_name}.ass")
    with open(ass_path, "w", encoding="utf-8") as f:
        f.write(
            to_ass_karaoke(
                segments,
                title=base_name,
                font_name=font_name,
                font_size=font_size,
                primary_color=primary_color,
                secondary_color=secondary_color,
                outline_color=outline_color,
                back_color=back_color,
                bold=bold,
            )
        )
    paths["ass"] = ass_path

    # JSON
    json_path = os.path.join(output_dir, f"{base_name}.json")
    with open(json_path, "w", encoding="utf-8") as f:
        f.write(to_json(segments, info))
    paths["json"] = json_path

    return paths


from video_to_subtitle.platform_utils import is_gradio_temp_path


def resolve_output_directory(
    video_path: str,
    custom_output_dir: Optional[str] = None,
    fallback_dir: Optional[str] = None,
) -> str:
    """
    Resolve the destination directory for subtitle files.
    - If custom_output_dir is provided: use it.
    - If video_path is in Gradio temporary cache: fallback to fallback_dir or ~/Downloads.
    - Otherwise: defaults to the same folder containing the input video.
    """
    if custom_output_dir and str(custom_output_dir).strip():
        out_dir = os.path.abspath(str(custom_output_dir).strip())
    elif is_gradio_temp_path(video_path):
        fallback = fallback_dir or os.path.expanduser("~/Downloads")
        out_dir = os.path.abspath(fallback)
    else:
        out_dir = os.path.dirname(os.path.abspath(video_path))
    os.makedirs(out_dir, exist_ok=True)
    return out_dir


