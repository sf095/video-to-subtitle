def test_resolve_output_directory_default():
    """Test default resolution places outputs in input video folder."""
    with tempfile.TemporaryDirectory() as temp_dir:
        fake_video = os.path.join(temp_dir, "media", "subfolder", "sample.mp4")
        os.makedirs(os.path.dirname(fake_video), exist_ok=True)
        with open(fake_video, "w") as f:
            f.write("fake video")

        resolved = resolve_output_directory(fake_video)
        expected = os.path.dirname(os.path.abspath(fake_video))
        assert resolved == expected
        assert os.path.isdir(resolved)


def test_resolve_output_directory_custom_override():
    """Test custom output directory override is respected."""
    with tempfile.TemporaryDirectory() as temp_dir:
        fake_video = os.path.join(temp_dir, "sample.mp4")
        custom_out = os.path.join(temp_dir, "custom_subtitles")

        resolved = resolve_output_directory(fake_video, custom_output_dir=custom_out)
        assert resolved == os.path.abspath(custom_out)
        assert os.path.isdir(resolved)


def test_resolve_output_directory_gradio_cache_fallback():
    """Test that videos in Gradio temporary cache fall back to ~/Downloads or fallback_dir."""
    fake_gradio_video = "/private/var/folders/37/2x/T/gradio/7a8b9c/uploaded_clip.mp4"
    with tempfile.TemporaryDirectory() as custom_fallback:
        resolved = resolve_output_directory(fake_gradio_video, fallback_dir=custom_fallback)
        assert resolved == os.path.abspath(custom_fallback)

    # Test default fallback to ~/Downloads
    resolved_default = resolve_output_directory(fake_gradio_video)
    assert resolved_default == os.path.expanduser("~/Downloads")


def test_srt_file_written_to_video_directory():
    """Test standard SRT file is created in video folder."""
    with tempfile.TemporaryDirectory() as temp_dir:
        video_folder = os.path.join(temp_dir, "my_movies")
        os.makedirs(video_folder, exist_ok=True)
        video_path = os.path.join(video_folder, "presentation.mp4")
        with open(video_path, "w") as f:
            f.write("dummy video data")

        # Mock segment
        words = [WordTiming(word=" Hello", start=0.0, end=1.0, probability=0.99)]
        segments = [SegmentTiming(id=0, start=0.0, end=1.0, text="Hello", words=words)]

        out_dir = resolve_output_directory(video_path)
        base_name = os.path.splitext(os.path.basename(video_path))[0]

        srt_path = export_srt(segments, out_dir, base_name)

        srt_expected = os.path.join(video_folder, "presentation.srt")

        assert os.path.exists(srt_expected), f"Expected {srt_expected} to exist"
        assert srt_path == srt_expected

        with open(srt_expected, "r", encoding="utf-8") as f:
            content = f.read()
            assert "Hello" in content


